/** «{p}» usw. ersetzen; unbekannte Platzhalter bleiben stehen. */
export const fuell = (s: string, w: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (m, k: string) => (k in w ? String(w[k]) : m));

export const einheitText = (einheit: string | undefined, s: BelegSprache) => {
  const e = einheit || 'Stk.';
  return DOK[s].einheiten[e] ?? e;
};

