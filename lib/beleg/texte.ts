/** Datum «15.11.2026» (in allen Sprachen Schweizer Schreibweise, wie auf dem PDF) */
export function datumText(d: Date | string | null | undefined, sprache: BelegSprache = 'de') {
  if (!d) return '';
  const x = typeof d === 'string' ? new Date(d.length === 10 ? `${d}T12:00:00` : d) : d;
  return x.toLocaleDateString(sprache === 'en' ? 'en-GB' : 'de-CH', { timeZone: 'Europe/Zurich', day: '2-digit', month: '2-digit', year: 'numeric' }).replace(/\//g, '.');
}
