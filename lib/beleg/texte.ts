/** Sprache eines Kontakts → Dokumentsprache (de/en/fr/it, übrige Sprachen der Website → Englisch) */
export function belegSprache(code?: string | null): BelegSprache {
  const c = (code ?? 'de').toLowerCase().slice(0, 2);
  return c === 'de' || c === 'en' || c === 'fr' || c === 'it' ? c : code ? 'en' : 'de';
}

